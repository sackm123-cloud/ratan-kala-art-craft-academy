-- Run this in Supabase Dashboard > SQL Editor.
create table if not exists public.admission_enquiries (
  id bigint generated by default as identity primary key,
  student_name text not null,
  parent_name text not null,
  age integer,
  phone text not null,
  email text,
  course text not null,
  message text,
  created_at timestamptz not null default now()
);

alter table public.admission_enquiries enable row level security;

-- Public website visitors may submit an enquiry, but cannot read enquiries.
create policy "Anyone can submit admission enquiries"
on public.admission_enquiries
for insert
to anon
with check (
  length(trim(student_name)) > 0
  and length(trim(parent_name)) > 0
  and length(trim(phone)) > 0
  and length(trim(course)) > 0
);

